class Typecasting{
    public static void main(String args[]){
        int x = 10;
        double y = x;
        System.out.println(y);
        double a = 10.5;
        int b = (int)a;
        System.out.println(b);
        int x1 = 1;
        int y1 = 5;
        int z = x1 ^= y1;
        System.out.print(z);
    }
}